// Design-system regression guard.
//
// Counts the five metrics in REDESIGN_PLAN.md section 4 across src/ and fails
// if any of them goes UP against scripts/design-baseline.json. A PR that brings
// a number down lowers the baseline in the same PR, so progress is visible and
// regressions are impossible to merge silently.
//
//   node scripts/design-check.cjs           check against baseline (exit 1 on regression)
//   node scripts/design-check.cjs --write   rewrite the baseline from current counts
//
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const BASELINE_FILE = path.join(__dirname, "design-baseline.json");

// src/contracts/ is generated from the Rust contract; src/debug/ is the
// deliberate escape hatch. Neither is part of the design surface.
const SCAN_DIR = "src";
const SCAN_EXT = [".tsx", ".ts", ".css", ".scss"];
const EXCLUDE = [/(^|\/)src\/contracts\//, /(^|\/)src\/debug\//];
// The token file is the one place raw colour values are allowed to live.
// receipt.css joins it: its tear tile is a data-URI SVG, and a data URI
// cannot read a custom property, so the receipt stock colour must be baked in.
const COLOUR_FILE_EXEMPT = [
  /(^|\/)src\/styles\/tokens\.css$/,
  /(^|\/)src\/components\/receipt\/receipt\.css$/,
];

const METRICS = [
  {
    key: "colourLiterals",
    label: "colour literals (hex/rgb/hsl)",
    target: 0,
    files: (f) => f.endsWith(".tsx") || f.endsWith(".css"),
    exempt: COLOUR_FILE_EXEMPT,
    // Matches #abc / #aabbcc / #aabbccdd, rgb()/rgba(), hsl()/hsla(),
    // oklch(), oklab(), and bare CSS colour keywords used as values.
    count: (text) =>
      matchAll(
        text,
        /#[0-9a-fA-F]{3,8}\b|\brgba?\s*\(|\bhsla?\s*\(|\boklch\s*\(|\boklab\s*\(/g,
      ),
  },
  {
    key: "inlineStyleBlocks",
    label: "inline style={{ }} blocks",
    target: 120,
    files: (f) => f.endsWith(".tsx"),
    count: (text) => matchAll(text, /\bstyle=\s*\{\{/g),
  },
  {
    key: "emoji",
    label: "emoji in .ts/.tsx",
    target: 0,
    files: (f) => f.endsWith(".ts") || f.endsWith(".tsx"),
    count: (text) =>
      matchAll(text, /\p{Extended_Pictographic}/gu).filter(
        // Guard against emoji-sequence joiners counted as pictographs.
        (m) => m !== "‍" && m !== "️",
      ),
  },
  {
    key: "cooperateDefectStrings",
    label: 'user-visible "Cooperate" / "Defect"',
    target: "glossary + inspector only",
    files: (f) => f.endsWith(".ts") || f.endsWith(".tsx"),
    // Word-boundary "Cooperate"/"Defect" in a quoted string or JSX text node.
    // Deliberately blunt: over-counting a handful of legitimate glossary and
    // inspector uses is cheaper than letting a new user-visible label slip
    // past the guard. Comments are stripped first so documentation about the
    // vocabulary doesn't count against the metric.
    count: (text) => {
      const code = text
        .replace(/\/\*[\s\S]*?\*\//g, " ")
        .replace(/(^|[^:])\/\/[^\n]*/g, "$1 ");
      return matchAll(
        code,
        /["'`](?:[^"'`]*\b)?\b(Cooperate|Defect)\b[^"'`]*["'`]|[>"'`]\s*(Cooperate|Defect)\s*[<"'`]/g,
      );
    },
  },
  {
    key: "glassPanel",
    label: "glass-panel uses",
    target: 0,
    files: () => true,
    count: (text) => matchAll(text, /glass-panel/g),
  },
];

function matchAll(text, re) {
  return text.match(re) || [];
}

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    const rel = path.relative(ROOT, abs).split(path.sep).join("/");
    if (EXCLUDE.some((re) => re.test(rel))) continue;
    if (entry.isDirectory()) walk(abs, out);
    else if (SCAN_EXT.includes(path.extname(entry.name))) out.push(rel);
  }
  return out;
}

function measure() {
  const files = walk(path.join(ROOT, SCAN_DIR));
  const counts = {};
  const offenders = {};

  for (const metric of METRICS) {
    let total = 0;
    const perFile = {};
    for (const file of files) {
      if (!metric.files(file)) continue;
      if (metric.exempt?.some((re) => re.test(file))) continue;
      const text = fs.readFileSync(path.join(ROOT, file), "utf8");
      const hits = metric.count(text);
      if (hits.length > 0) {
        perFile[file] = hits.length;
        total += hits.length;
      }
    }
    counts[metric.key] = total;
    offenders[metric.key] = perFile;
  }

  return { counts, offenders, fileCount: files.length };
}

function loadBaseline() {
  if (!fs.existsSync(BASELINE_FILE)) return null;
  return JSON.parse(fs.readFileSync(BASELINE_FILE, "utf8"));
}

const { counts, offenders, fileCount } = measure();
const baseline = loadBaseline();
const write = process.argv.includes("--write");

if (write || !baseline) {
  const payload = {
    _comment:
      "Generated by scripts/design-check.cjs --write. Counts must never rise.",
    updated: new Date().toISOString().slice(0, 10),
    ...counts,
  };
  fs.writeFileSync(BASELINE_FILE, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(
    baseline
      ? `design:check baseline updated (${fileCount} files scanned)\n` +
          Object.entries(counts)
            .map(([k, v]) => `  ${k}: ${v}`)
            .join("\n")
      : `design:check baseline created (${fileCount} files scanned)\n` +
          Object.entries(counts)
            .map(([k, v]) => `  ${k}: ${v}`)
            .join("\n") +
          "\n\nReview these numbers against REDESIGN_PLAN.md section 4 before committing.",
  );
  process.exit(0);
}

const regressions = [];
const improvements = [];
for (const metric of METRICS) {
  const key = metric.key;
  const now = counts[key];
  const before = baseline[key];
  if (typeof before !== "number") {
    regressions.push(`${key}: no baseline number (expected ${before})`);
    continue;
  }
  if (now > before) {
    const worst = Object.entries(offenders[key])
      .sort((a, b) => b[1] - a[1])
      .slice(0, 5)
      .map(([f, n]) => `${f} (${n})`)
      .join(", ");
    regressions.push(
      `${metric.label}: ${before} -> ${now} (+${now - before})\n      ${worst}`,
    );
  } else if (now < before) {
    improvements.push(
      `${metric.label}: ${before} -> ${now} (-${before - now})`,
    );
  }
}

const width = Math.max(...METRICS.map((m) => m.label.length));
console.log(`design:check — ${fileCount} files scanned under ${SCAN_DIR}/\n`);
for (const metric of METRICS) {
  const key = metric.key;
  const now = counts[key];
  const before = baseline[key];
  const delta = now - before;
  const mark = delta > 0 ? "▲" : delta < 0 ? "▼" : "=";
  const change = delta === 0 ? "" : ` (${delta > 0 ? "+" : ""}${delta})`;
  console.log(
    `  ${mark} ${metric.label.padEnd(width)}  ${String(before).padStart(4)} -> ${String(now).padStart(4)}${change}   target ${metric.target}`,
  );
}

if (improvements.length) {
  console.log(
    `\nImproved — lower the baseline in this same PR:\n  ${improvements.join("\n  ")}`,
  );
}

if (regressions.length) {
  console.error(
    `\n✗ design regressions:\n  ${regressions.join("\n  ")}\n\n` +
      `Every colour must come from tokens.css, every emoji must become a mark\n` +
      `or an icon, and style={{}} blocks must convert to classes. See\n` +
      `REDESIGN_PLAN.md section 3 (recipe) and section 8 (review blockers).\n`,
  );
  process.exit(1);
}

console.log("\n✓ no regressions");
